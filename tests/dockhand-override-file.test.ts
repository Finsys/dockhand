/**
 * buildDockhandOverrideFile: the .env.dockhand contents shared by both git-stack
 * deploy paths (local writeFileSync + Hawser stackFiles). A zero-var git stack must
 * still produce a (header-only) file so a compose referencing env_file: .env.dockhand
 * can resolve it (#1336).
 */
import { describe, it, expect } from 'bun:test';
import { buildDockhandOverrideFile, planDockhandOverrideFile } from '../src/lib/server/dockhand-override-file';

const HEADER = '# Auto-generated by Dockhand. Do not edit - changes will be overwritten on next deploy.\n';

describe('buildDockhandOverrideFile', () => {
	it('returns a header-only file (no trailing blank line) for ZERO vars', () => {
		const out = buildDockhandOverrideFile({});
		expect(out).toBe(
			'# Auto-generated by Dockhand. Do not edit - changes will be overwritten on next deploy.\n'
		);
		// exactly one trailing newline - no empty value line that could clear a repo var
		expect(out.endsWith('\n')).toBe(true);
		expect(out.endsWith('\n\n')).toBe(false);
	});

	it('writes KEY=value lines under the header', () => {
		const out = buildDockhandOverrideFile({ A: '1', B: 'two' });
		expect(out).toContain('A=1');
		expect(out).toContain('B=two');
		expect(out.startsWith('# Auto-generated')).toBe(true);
		expect(out.endsWith('\n')).toBe(true);
	});

	it('keeps values verbatim (including = and spaces)', () => {
		const out = buildDockhandOverrideFile({ URL: 'https://x/y?a=b c' });
		expect(out).toContain('URL=https://x/y?a=b c');
	});
});

describe('planDockhandOverrideFile', () => {
	it('does nothing for a non-git stack (useOverrideFile false)', () => {
		const plan = planDockhandOverrideFile(false, { FOO: 'bar' });
		expect(plan.shouldWrite).toBe(false);
		expect(plan.attachCliArg).toBe(false);
		expect(plan.content).toBe('');
	});

	it('writes the file and attaches --env-file when overrides exist', () => {
		const plan = planDockhandOverrideFile(true, { APP_VALUE: 'overridden' });
		expect(plan.shouldWrite).toBe(true);
		expect(plan.attachCliArg).toBe(true);
		expect(plan.content).toContain('APP_VALUE=overridden');
	});

	it('writes a header-only file but omits --env-file when overrides are removed', () => {
		// The removed-override case: the file must still be written so a stale value on
		// disk is overwritten and env_file: .env.dockhand resolves, but --env-file must
		// be left off so adjacent-.env auto-discovery is preserved.
		const plan = planDockhandOverrideFile(true, {});
		expect(plan.shouldWrite).toBe(true);
		expect(plan.content).toBe(HEADER);
		expect(plan.attachCliArg).toBe(false);
	});

	it('treats undefined envVars like an empty override set', () => {
		const plan = planDockhandOverrideFile(true, undefined);
		expect(plan.shouldWrite).toBe(true);
		expect(plan.attachCliArg).toBe(false);
		expect(plan.content).toBe(HEADER);
	});
});
